import { objectKey } from "typespec-http-zod";
import { inputSchemaName, inputSchemaOf, schemaImportsOf } from "./handlers.js";
import {
	type ArgumentPlan,
	type BaseResolution,
	type CallPlan,
	type DefaultLiteral,
	type InputFieldPlan,
	type OutputFieldPlan,
	RUNTIME_SCALARS,
	type SchemaPlan,
	type TypeDef,
	type TypeRef,
} from "./model.js";

/**
 * **`graphql.gen.ts`, from the plan: graphql-js constructors and `createSchema`.**
 *
 * Text, written as the sibling emitters write theirs: no code-generation library. Every named type
 * is built once per `createSchema` call, inside one `types` object whose fields are thunks, so
 * recursive types work and nothing parses SDL at start-up. The file is this text followed by
 * `renderOperations`' (handlers.ts); the imports here cover both.
 *
 * Pure: it reads `model.ts` and the library's `objectKey`, never the compiler.
 */

/** The banner every generated file carries, in the form typespec-http-mcp writes its own. */
export function generatedBanner(hint: string | undefined): string {
	const second =
		hint === undefined
			? "// Recompile the spec that produced it; edits here are overwritten on the next run."
			: `// Regenerate with: ${hint}`;
	return `// GENERATED by typespec-http-graphql from the TypeSpec service definition. DO NOT EDIT.\n${second}\n`;
}

/** Where emitted code imports its runtime from: the copy this package writes beside it. */
export const RUNTIME_MODULE = "./graphql-runtime.gen.js";

const BUILT_IN_SCALARS: Readonly<Record<string, string>> = {
	String: "GraphQLString",
	Int: "GraphQLInt",
	Float: "GraphQLFloat",
	Boolean: "GraphQLBoolean",
	ID: "GraphQLID",
};

/** What the rendered text uses, collected while rendering so nothing unused is imported. */
interface Uses {
	readonly graphqlValues: Set<string>;
	readonly graphqlTypes: Set<string>;
	readonly runtimeValues: Set<string>;
	/** True when the plan has a `byStatus` projection, so resolvers are handed `STATUS_CODES`. */
	readonly statusCodes: boolean;
}

/** The field-config type every generated map is checked against. */
function fieldConfigType(uses: Uses): string {
	uses.graphqlTypes.add("GraphQLFieldConfig");
	return "GraphQLFieldConfig<Record<string, unknown>, X>";
}

function typeExpression(ref: TypeRef, uses: Uses): string {
	let inner: string;
	if (ref.kind === "list") {
		uses.graphqlValues.add("GraphQLList");
		inner = `new GraphQLList(${typeExpression(ref.of, uses)})`;
	} else {
		const builtIn = BUILT_IN_SCALARS[ref.name];
		if (builtIn !== undefined) uses.graphqlValues.add(builtIn);
		inner = builtIn ?? `types.${ref.name}`;
	}
	if (!ref.nonNull) return inner;
	uses.graphqlValues.add("GraphQLNonNull");
	return `new GraphQLNonNull(${inner})`;
}

function describe(description: string | undefined): readonly string[] {
	return description === undefined ? [] : [`description: ${JSON.stringify(description)}`];
}

function deprecate(reason: string | undefined): readonly string[] {
	return reason === undefined ? [] : [`deprecationReason: ${JSON.stringify(reason)}`];
}

/** `{ a, b }` on one line, or `{}`. */
function inline(parts: readonly string[]): string {
	return parts.length === 0 ? "{}" : `{ ${parts.join(", ")} }`;
}

/** A block opening on a line indented `indent`: one part per line, one tab deeper. */
function block(parts: readonly string[], indent: string): string {
	return parts.length === 0
		? "{}"
		: `{\n${parts.map((part) => `${indent}\t${part},`).join("\n")}\n${indent}}`;
}

/** The OpenAPI requirements as a TypeScript literal, as typespec-http-mcp's `renderSecurity`. */
function renderSecurity(requirements: CallPlan["security"]): string {
	return `[${requirements
		.map((requirement) =>
			inline(
				Object.entries(requirement).map(
					([scheme, scopes]) =>
						`${JSON.stringify(scheme)}: [${scopes.map((s) => JSON.stringify(s)).join(", ")}]`,
				),
			),
		)
		.join(", ")}]`;
}

/** The `CallRuntime` literal a root field or link hands `resolverFor`. */
function callLiteral(call: CallPlan, args: readonly ArgumentPlan[], indent: string): string {
	const connection =
		call.connection === undefined
			? "undefined"
			: JSON.stringify({
					items: call.connection.items,
					next: call.connection.next,
					first: call.connection.first,
					after: call.connection.after,
					...(call.connection.maximum === undefined ? {} : { maximum: call.connection.maximum }),
				});
	return block(
		[
			`kind: ${JSON.stringify(call.kind)}`,
			`operationId: ${JSON.stringify(call.operationId)}`,
			`authentication: ${JSON.stringify(call.authentication)}`,
			`security: ${renderSecurity(call.security)}`,
			`input: ${call.inputSchema}`,
			`arms: ${call.responses}`,
			`bound: ${JSON.stringify(call.bound)}`,
			`supplied: ${JSON.stringify(call.supplied)}`,
			`args: ${argumentRulesOf(args)}`,
			`projection: ${JSON.stringify(call.projection)}`,
			`connection: ${connection}`,
		],
		indent,
	);
}

/**
 * A default as graphql-js 17's `default: { literal }`: the constant AST node itself, so graphql-js
 * coerces it through the type's own `coerceInputLiteral` and introspection prints it, with no
 * `valueToLiteral` asked of a custom scalar.
 */
function defaultConfig(literal: DefaultLiteral | undefined, uses: Uses): readonly string[] {
	if (literal === undefined) return [];
	uses.graphqlValues.add("Kind");
	const node =
		literal.kind === "NULL"
			? "{ kind: Kind.NULL }"
			: `{ kind: Kind.${literal.kind}, value: ${JSON.stringify(literal.value)} }`;
	return [`default: { literal: ${node} }`];
}

/**
 * One argument's or input field's wire rule, each key only where its default does not hold, or
 * `undefined` where none does. Written into code (`CallRuntime.args`, `INPUT_RULES`), never into the
 * schema's `extensions`, which a rebuilt or transformed schema drops.
 */
function wireRuleOf(
	input: Pick<ArgumentPlan, "name" | "wire" | "dropNull" | "nullIfAbsent"> & {
		readonly merge?: boolean;
	},
): Readonly<Record<string, string | boolean>> | undefined {
	const rule: Record<string, string | boolean> = {};
	if (input.merge === true) rule["merge"] = true;
	else if (input.wire !== input.name) rule["wire"] = input.wire;
	if (input.dropNull) rule["dropNull"] = true;
	if (input.nullIfAbsent) rule["nullIfAbsent"] = true;
	return Object.keys(rule).length === 0 ? undefined : rule;
}

/** A field's argument rules, as the `args` of its `CallRuntime`. */
function argumentRulesOf(args: readonly ArgumentPlan[]): string {
	const rules: Record<string, unknown> = {};
	for (const argument of args) {
		const rule = wireRuleOf(argument);
		if (rule !== undefined) rules[argument.name] = rule;
	}
	return JSON.stringify(rules);
}

/** Every input object type's field rules, as the `INPUT_RULES` literal every resolver is handed. */
function inputRulesOf(plan: SchemaPlan): string {
	const rules: Record<string, Record<string, unknown>> = {};
	for (const def of plan.types) {
		if (def.kind !== "input") continue;
		for (const field of def.fields) {
			const rule = wireRuleOf(field);
			if (rule !== undefined) (rules[def.name] ??= {})[field.name] = rule;
		}
	}
	return JSON.stringify(rules, null, "\t");
}

/** One argument, with its deprecation and default where they hold. */
function argumentConfig(argument: ArgumentPlan, uses: Uses): string {
	const parts = [
		`type: ${typeExpression(argument.type, uses)}`,
		...describe(argument.description),
		...deprecate(argument.deprecationReason),
		...defaultConfig(argument.defaultValue, uses),
	];
	return `${objectKey(argument.name)}: ${inline(parts)}`;
}

/** One output field's config, on a line indented `indent`. */
function outputFieldConfig(field: OutputFieldPlan, uses: Uses, indent: string): string {
	const parts = [
		`type: ${typeExpression(field.type, uses)}`,
		...describe(field.description),
		...deprecate(field.deprecationReason),
	];
	if (field.arguments.length > 0) {
		parts.push(
			`args: ${block(
				field.arguments.map((argument) => argumentConfig(argument, uses)),
				`${indent}\t`,
			)}`,
		);
	}
	if (field.call !== undefined) {
		uses.runtimeValues.add("resolverFor");
		parts.push(
			`resolve: resolverFor(${callLiteral(field.call, field.arguments, `${indent}\t`)}, handlersFor, deps, INPUT_RULES${uses.statusCodes ? ", STATUS_CODES" : ""})`,
		);
	} else {
		/**
		 * **Every field reads its own property, never graphql-js's default resolver.** The default reads
		 * `source[name]` through the prototype chain and CALLS a function it finds, so a body with no
		 * `constructor` key answered `Object` called on the arguments: "String cannot represent
		 * value: {}" for a field that should be `null`.
		 */
		uses.runtimeValues.add("wireField");
		parts.push(`resolve: wireField(${JSON.stringify(field.wire)})`);
	}
	/**
	 * The cost directives, repeated so a validation rule can read them from the runtime schema
	 * (design.md), and **the operation a field calls, on the fields that call one**: every field has
	 * a resolver, so graphql-js's `isDefaultResolver` cannot tell a tracer a handler call from a
	 * property read, and `operationId` does, under the name the REST route's spans carry too.
	 */
	const extensions = [
		...field.directives.map((d) => `${d.name}: ${JSON.stringify(d.arguments)}`),
		...(field.call === undefined ? [] : [`operationId: ${JSON.stringify(field.call.operationId)}`]),
	];
	if (extensions.length > 0) parts.push(`extensions: ${inline(extensions)}`);
	return `${objectKey(field.name)}: ${block(parts, indent)}`;
}

/** One input field's config, on a line indented `indent`, with its deprecation and default. */
function inputFieldConfig(field: InputFieldPlan, uses: Uses, indent: string): string {
	const parts = [
		`type: ${typeExpression(field.type, uses)}`,
		...describe(field.description),
		...deprecate(field.deprecationReason),
		...defaultConfig(field.defaultValue, uses),
	];
	return `${objectKey(field.name)}: ${block(parts, indent)}`;
}

/**
 * A field map checked against `GraphQLFieldConfig`, with the consumer's extension merged in, as an
 * `extendFields(...)` call opening on a line indented `indent`.
 */
function fieldMap(
	typeName: string,
	fields: readonly OutputFieldPlan[],
	extension: string,
	uses: Uses,
	indent: string,
): string {
	uses.runtimeValues.add("extendFields");
	const configs = fields.map((field) => outputFieldConfig(field, uses, `${indent}\t\t`));
	return `extendFields<${fieldConfigType(uses)}>(\n${indent}\t${JSON.stringify(typeName)},\n${indent}\t${block(configs, `${indent}\t`)},\n${indent}\t${extension},\n${indent})`;
}

const SCALAR_NAMES: ReadonlySet<string> = new Set(RUNTIME_SCALARS);

/** One entry of the `types` object, on a line indented `indent`: `Name: new GraphQL...Type({...})`. */
function typeEntry(def: TypeDef, uses: Uses, indent: string): string {
	const name = JSON.stringify(def.name);
	switch (def.kind) {
		case "object": {
			uses.graphqlValues.add("GraphQLObjectType");
			const fields = fieldMap(
				def.name,
				def.fields,
				`extension?.fields?.${def.name}`,
				uses,
				`${indent}\t\t`,
			);
			return `${def.name}: new GraphQLObjectType(${block(
				[
					`name: ${name}`,
					...describe(def.description),
					...interfacesOf(def.interfaces),
					`fields: () =>\n${indent}\t\t${fields}`,
				],
				indent,
			)})`;
		}
		case "interface": {
			/**
			 * The shared fields alone, every implementer's own field resolving the value. A source
			 * model's interface is no field's type, so it needs no resolver: a client selects one in a
			 * fragment. A `@discriminator` base's is, and resolves a value by its rule.
			 */
			uses.graphqlValues.add("GraphQLInterfaceType");
			const resolve: string[] = [];
			if (def.resolveBy !== undefined) {
				uses.runtimeValues.add("baseTypeOf");
				resolve.push(`resolveType: baseTypeOf(${baseRuleOf(def.resolveBy.rule)})`);
			}
			const fields = def.fields.map(
				(field) =>
					`${objectKey(field.name)}: ${inline([
						`type: ${typeExpression(field.type, uses)}`,
						...describe(field.description),
						...deprecate(field.deprecationReason),
					])}`,
			);
			return `${def.name}: new GraphQLInterfaceType(${block(
				[
					`name: ${name}`,
					...describe(def.description),
					...interfacesOf(def.interfaces),
					`fields: () => (${block(fields, `${indent}\t`)})`,
					...resolve,
				],
				indent,
			)})`;
		}
		case "input": {
			uses.graphqlValues.add("GraphQLInputObjectType");
			const fields = def.fields.map((field) => inputFieldConfig(field, uses, `${indent}\t\t`));
			return `${def.name}: new GraphQLInputObjectType(${block(
				[
					`name: ${name}`,
					...describe(def.description),
					`fields: () => (${block(fields, `${indent}\t`)})`,
				],
				indent,
			)})`;
		}
		case "enum": {
			uses.graphqlValues.add("GraphQLEnumType");
			const values = def.values.map(
				(value) =>
					`${value.name}: ${inline([
						`value: ${JSON.stringify(value.wire)}`,
						...describe(value.description),
						...deprecate(value.deprecationReason),
					])}`,
			);
			return `${def.name}: new GraphQLEnumType(${block(
				[`name: ${name}`, ...describe(def.description), `values: ${block(values, `${indent}\t`)}`],
				indent,
			)})`;
		}
		case "union": {
			uses.graphqlValues.add("GraphQLUnionType");
			let resolveType: string;
			if (def.resolveBy.kind === "member") {
				uses.runtimeValues.add("memberTypeOf");
				resolveType = "memberTypeOf";
			} else {
				uses.runtimeValues.add("discriminatedTypeOf");
				resolveType = `discriminatedTypeOf(${JSON.stringify(def.resolveBy.property)}, ${JSON.stringify(def.resolveBy.mapping)})`;
			}
			return `${def.name}: new GraphQLUnionType(${block(
				[
					`name: ${name}`,
					...describe(def.description),
					`types: () => [${def.members.map((member) => `types.${member}`).join(", ")}]`,
					`resolveType: ${resolveType}`,
				],
				indent,
			)})`;
		}
		case "scalar": {
			if (!SCALAR_NAMES.has(def.name)) {
				throw new Error(
					`typespec-http-graphql internal invariant: the plan declares a scalar '${def.name}' the runtime does not define`,
				);
			}
			/**
			 * **The runtime's own scalar, never re-described here.** The plan's description and URL come
			 * from `SCALAR_DEFINITIONS` and the runtime's from its hand copy; `schema.graphql` prints the
			 * first and this module serves the second, so the SDL oracle sees any drift between them.
			 */
			uses.runtimeValues.add("SCALARS");
			return `${def.name}: SCALARS.${def.name}`;
		}
	}
}

/** An object or interface type's `interfaces`, none where it implements none. */
/** A base's rule as code: each subtype's validator by the identifier `schemas.gen.ts` exports. */
function baseRuleOf(rule: BaseResolution): string {
	const mapping = Object.entries(rule.mapping).map(
		([key, member]) =>
			`${objectKey(key)}: { schema: ${member.schema}, ${"type" in member ? `type: ${JSON.stringify(member.type)}` : `rule: ${baseRuleOf(member.rule)}`} }`,
	);
	return `{ property: ${JSON.stringify(rule.property)}, mapping: { ${mapping.join(", ")} }, base: ${JSON.stringify(rule.base)} }`;
}

/** Every validator a base's rule names, nested bases' included, for the `schemas.gen.ts` import. */
function validatorsOf(rule: BaseResolution): string[] {
	return Object.values(rule.mapping).flatMap((member) => [
		member.schema,
		...("rule" in member ? validatorsOf(member.rule) : []),
	]);
}

function interfacesOf(interfaces: readonly string[] | undefined): string[] {
	return interfaces === undefined || interfaces.length === 0
		? []
		: [`interfaces: () => [${interfaces.map((each) => `types.${each}`).join(", ")}]`];
}

/** The graphql-js class each kind of named type is an instance of, for `GraphQLTypes`. */
const CLASS_OF: { readonly [K in TypeDef["kind"]]: string } = {
	object: "GraphQLObjectType",
	interface: "GraphQLInterfaceType",
	input: "GraphQLInputObjectType",
	enum: "GraphQLEnumType",
	union: "GraphQLUnionType",
	scalar: "GraphQLScalarType",
};

/** Every operation the plan names is called by some field, and every call names a planned one. */
function checkOperations(plan: SchemaPlan): void {
	const planned = new Set(plan.operations.map((operation) => operation.route.operationId));
	const called = new Set<string>();
	const fields = [
		...plan.query,
		...plan.mutation,
		...plan.types.flatMap((def) => (def.kind === "object" ? def.fields : [])),
	];
	for (const field of fields) {
		if (field.call !== undefined) called.add(field.call.operationId);
	}
	const uncalled = [...planned].filter((id) => !called.has(id));
	const unplanned = [...called].filter((id) => !planned.has(id));
	if (uncalled.length > 0 || unplanned.length > 0) {
		throw new Error(
			`typespec-http-graphql internal invariant: plan.operations and the fields' calls disagree ` +
				`(uncalled: ${uncalled.join(", ") || "none"}; unplanned: ${unplanned.join(", ") || "none"})`,
		);
	}
}

/**
 * `graphql.gen.ts` up to the handler types, which `renderOperations` appends.
 *
 * `sealed` is the library's resolved `seal-object-schemas`, which the merged input schemas follow;
 * `hint` is its `regenerate-hint`, for the banner.
 */
export function renderSchemaModule(
	plan: SchemaPlan,
	options: { readonly sealed: boolean; readonly hint: string | undefined },
): string {
	checkOperations(plan);
	const uses: Uses = {
		graphqlValues: new Set(["GraphQLObjectType", "GraphQLSchema"]),
		graphqlTypes: new Set(["GraphQLFieldConfigMap"]),
		runtimeValues: new Set(["extendFields"]),
		statusCodes: Object.keys(plan.statusCodes).length > 0,
	};

	const entries = plan.types.map((def) => typeEntry(def, uses, "\t\t"));
	const query = fieldMap("Query", plan.query, "extension?.query", uses, "\t\t\t");
	const mutation = fieldMap("Mutation", plan.mutation, "extension?.mutation", uses, "\t");
	if (plan.usesCost) {
		uses.graphqlValues.add("specifiedDirectives");
		uses.runtimeValues.add("CostDirective");
		uses.runtimeValues.add("ListSizeDirective");
	}
	for (const def of plan.types) uses.graphqlTypes.add(CLASS_OF[def.kind]);

	const typesInterface = plan.types
		.map((def) => `\treadonly ${def.name}: ${CLASS_OF[def.kind]};`)
		.join("\n");
	const extensionFields = plan.types
		.filter((def) => def.kind === "object")
		.map((def) => `\t\treadonly ${def.name}?: GraphQLFieldConfigMap<unknown, X>;`)
		.join("\n");

	const hasOperations = plan.operations.length > 0;
	const graphqlTypeOnly = [...uses.graphqlTypes].filter((name) => !uses.graphqlValues.has(name));
	const schemaImports = [
		...new Set([
			...schemaImportsOf(plan.operations),
			...plan.types.flatMap((def) =>
				def.kind === "interface" && def.resolveBy !== undefined
					? validatorsOf(def.resolveBy.rule)
					: [],
			),
		]),
	].toSorted();
	const imports = [
		`import { ${[...uses.graphqlValues].toSorted().join(", ")} } from "graphql";`,
		`import type { ${graphqlTypeOnly.toSorted().join(", ")} } from "graphql";`,
		...(hasOperations ? ['import { z } from "zod";'] : []),
		`import { ${[...uses.runtimeValues].toSorted().join(", ")} } from ${JSON.stringify(RUNTIME_MODULE)};`,
		`import type { ${["GraphQLDeps", ...(hasOperations ? ["Awaitable", "InputRules"] : []), ...(uses.statusCodes ? ["StatusCodes"] : [])].toSorted().join(", ")} } from ${JSON.stringify(RUNTIME_MODULE)};`,
		...(schemaImports.length === 0
			? []
			: [`import { ${schemaImports.join(", ")} } from "./schemas.gen.js";`]),
	].join("\n");

	const inputConsts = [
		...plan.operations.map(
			(operation) =>
				`const ${inputSchemaName(operation.route.operationId)} = ${inputSchemaOf(operation, options.sealed)};`,
		),
		...(hasOperations
			? [
					"",
					"/** How each input object's fields reach a handler's input: see `InputRules` in the runtime. */",
					`const INPUT_RULES: InputRules = ${inputRulesOf(plan)};`,
					...(uses.statusCodes
						? [
								"",
								"/** The code each status a `default` or ranged response may answer with is given. */",
								`const STATUS_CODES: StatusCodes = ${JSON.stringify(plan.statusCodes, null, "\t")};`,
							]
						: []),
				]
			: []),
	].join("\n");

	/** Every parameter is unread when nothing calls a handler; `noUnusedParameters` refuses that. */
	const u = hasOperations ? "" : "_";
	const directives = plan.usesCost
		? "\n\t\tdirectives: [...specifiedDirectives, CostDirective, ListSizeDirective],"
		: "";

	return `${generatedBanner(options.hint)}
${imports}
${inputConsts === "" ? "" : `\n${inputConsts}\n`}
/** Every named type of the schema \`createSchema\` builds, for an extension's fields to use. */
export interface GraphQLTypes {
${typesInterface}
}

/**
 * Hand-written fields no operation provides, built from the generated types: the escape hatch.
 * A collision with a generated field throws when the schema is built, naming both.
 */
export interface GraphQLExtension<X> {
	readonly query?: GraphQLFieldConfigMap<unknown, X>;
	readonly mutation?: GraphQLFieldConfigMap<unknown, X>;
	readonly fields?: {
${extensionFields}
	};
}

/**
 * The GraphQL schema this service declares, every field resolved by calling the same handler the
 * HTTP route calls, through the same validation.
 *
 * **Build it once, at module scope.** Per-request state arrives through the context value \`X\`, which
 * the per-request call memo is keyed on, so a server must hand each request its own object.
 * **\`extend\` must not read a type's fields**: they are built after it returns.
 */
export function createSchema<X extends object, C, T extends GraphQLOperations<C>>(
	${u}handlersFor: (context: X) => GraphQLExhaustive<T>,
	${u}deps: GraphQLDeps<X, C>,
	extend?: (types: GraphQLTypes) => GraphQLExtension<X>,
): GraphQLSchema {
	const types: GraphQLTypes = ${block(entries, "\t")};
	const extension = extend?.(types);
	const mutationFields = ${mutation};
	return new GraphQLSchema({
		query: new GraphQLObjectType({
			name: "Query",
			fields: ${query},
		}),
		mutation:
			Object.keys(mutationFields).length === 0
				? undefined
				: new GraphQLObjectType({ name: "Mutation", fields: mutationFields }),
		types: Object.values(types),${directives}
	});
}
`;
}
