import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
	type EmitContext,
	emitFile,
	NoTarget,
	type Program,
	resolvePath,
} from "@typespec/compiler";
import { emitHttpZod, type EmittedService } from "typespec-http-zod";
import { collisionsFor } from "./coexistence.js";
import { renderOperations } from "./handlers.js";
import { PACKAGE_NAME, reportDiagnostic } from "./lib.js";
import { planService } from "./plan.js";
import { renderSchemaModule } from "./render.js";
import { renderSdl } from "./sdl.js";
import { type SurfaceDiagnostic, surfaceOf } from "./surface.js";

/** Where this package's own runtime source lives, to be copied beside the generated code. */
const RUNTIME_SOURCE = fileURLToPath(new URL("../../src/runtime.ts", import.meta.url));

/** The header the emitted runtime carries, matching every other generated file. */
function runtimeBanner(hint: string | undefined): string {
	const second =
		hint === undefined
			? "// A copy of this package's runtime, emitted so the generated code imports no package at run time."
			: `// Regenerate with: ${hint}`;
	return `// GENERATED by typespec-http-graphql. DO NOT EDIT.\n${second}\n`;
}

/**
 * What reports a diagnostic `surface.ts` or `plan.ts` decided, under this library's name, **once per
 * program**.
 *
 * **Their code is a string, chosen from `lib.ts`'s table**, so the typed `reportDiagnostic` cannot
 * check it statically. The compiler checks it when the diagnostic is created: an unknown code
 * throws `Unexpected diagnostic code`, so a stage that invented one fails every compile that
 * reaches it rather than reporting nothing.
 *
 * **Once**, because each service is planned on its own and the compiler keeps every diagnostic it
 * is given: a type two services project, or a `@json` naming one, was warned once per service at the
 * one declaration it is about. Two are the same where target, code and format are.
 */
function decidedReporter(program: Program): (diagnostic: SurfaceDiagnostic) => void {
	const report = reportDiagnostic as unknown as (
		program: Program,
		diagnostic: SurfaceDiagnostic,
	) => void;
	const reported = new Map<SurfaceDiagnostic["target"], Set<string>>();
	return (diagnostic) => {
		const key = `${diagnostic.code}\u0000${JSON.stringify(diagnostic.format)}`;
		const seen = reported.get(diagnostic.target) ?? new Set<string>();
		if (seen.has(key)) return;
		seen.add(key);
		reported.set(diagnostic.target, seen);
		report(program, diagnostic);
	};
}

/**
 * **`emitted + dropped === declared`, asserted from structured counts**, as typespec-http-mcp
 * asserts `emitted + refused === selected`. A silent drop is then impossible: the numbers stop adding
 * up. `declared` is `surfaceOf`'s, never the raw accessors', which count a versioned spec's
 * declarations once per projection.
 */
function assertAccounted(
	service: string,
	emitted: number,
	dropped: number,
	declared: number,
): void {
	if (emitted + dropped !== declared) {
		throw new Error(
			`typespec-http-graphql internal invariant: ${emitted} emitted + ${dropped} dropped ` +
				`!== ${declared} declared for '${service}'`,
		);
	}
}

/** One service: its surface, its plan, and the three files, or none of them. */
async function emitService(
	program: Program,
	emitted: EmittedService,
	reportDecided: (diagnostic: SurfaceDiagnostic) => void,
): Promise<void> {
	const service = emitted.service.namespace.name;
	const surface = surfaceOf(program, emitted);
	for (const diagnostic of [...surface.dropped, ...surface.warnings]) reportDecided(diagnostic);

	const noFields = (): void => {
		reportDiagnostic(program, {
			code: "no-fields-declared",
			target: emitted.service.namespace,
			format: { service },
		});
	};

	/**
	 * **No field, no file.** A service the spec does not expose gets the library's validators and
	 * nothing of this emitter's: not even the runtime, which nothing would import.
	 */
	if (surface.roots.length + surface.links.length === 0) {
		assertAccounted(service, 0, surface.dropped.length, surface.declared);
		noFields();
		return;
	}

	const planned = planService(program, emitted, surface);
	for (const diagnostic of planned.warnings) reportDecided(diagnostic);
	assertAccounted(
		service,
		planned.emitted,
		surface.dropped.length + planned.dropped,
		surface.declared,
	);
	if (planned.emitted === 0) {
		noFields();
		return;
	}

	const hint = emitted.options.regenerateHint;
	await emitFile(program, {
		path: resolvePath(emitted.outputDir, "graphql-runtime.gen.ts"),
		content: `${runtimeBanner(hint)}${readFileSync(RUNTIME_SOURCE, "utf8")}`,
	});
	await emitFile(program, {
		path: resolvePath(emitted.outputDir, "graphql.gen.ts"),
		content: `${renderSchemaModule(planned.plan, {
			sealed: emitted.options.sealObjectSchemas,
			hint,
		})}\n${renderOperations(
			planned.plan.operations,
			emitted.routes.map((route) => route.operationId),
		)}`,
	});
	await emitFile(program, {
		path: resolvePath(emitted.outputDir, "schema.graphql"),
		content: renderSdl(planned.plan),
	});
}

/**
 * Run the library, then write each service's GraphQL surface beside what it wrote.
 *
 * **This file may import only `./lib.js`, its own modules, the library's public API and external
 * packages**, the rule `typespec-http-mcp` holds its own entry point to: it makes "the published
 * API is sufficient to build an emitter on" true by construction.
 */
export async function $onEmit(context: EmitContext): Promise<void> {
	/**
	 * Raised once per program, before anything is written: it is about the arrangement, not about
	 * any one service.
	 */
	for (const collision of collisionsFor(context.program, PACKAGE_NAME, context.emitterOutputDir)) {
		reportDiagnostic(context.program, {
			code: "shared-output-dir",
			target: NoTarget,
			format: { emitter: collision.emitter, differing: collision.differing.join(", ") },
		});
	}
	const reportDecided = decidedReporter(context.program);
	for (const emitted of await emitHttpZod(context)) {
		await emitService(context.program, emitted, reportDecided);
	}
}
