import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import {
	graphql,
	type GraphQLSchema,
	isInputObjectType,
	isObjectType,
	validateSchema,
} from "graphql";
import { beforeAll, describe, expect, it } from "vitest";
import { type CompiledFixture, compileFixture } from "../support/compile-fixture.js";
import { sdlAgreement } from "../support/sdl-agreement.js";
import { typecheckEmitted } from "../support/typecheck-emitted.js";

/**
 * **The emitter end to end: what one compile writes, and that it is what it claims to be.**
 *
 * Every fixture here is compiled through `$onEmit`, so these arms see the files a consumer gets:
 * the three GraphQL files beside the library's validators, typechecked under a consumer's settings,
 * imported and executed, and `schema.graphql` graded against the schema the module builds.
 */

const here = fileURLToPath(new URL(".", import.meta.url));
const runtimeSource = fileURLToPath(new URL("../../src/runtime.ts", import.meta.url));
const GRAPHQL_FILES = ["graphql.gen.ts", "graphql-runtime.gen.ts", "schema.graphql"] as const;

interface Generated {
	readonly createSchema: (handlersFor: (context: object) => object, deps: object) => GraphQLSchema;
}

const deps = { authorize: () => "allow" as const, context: () => "caller" };

async function runtimeSchemaOf(outDir: string, handlers: object = {}): Promise<GraphQLSchema> {
	const generated = (await import(join(outDir, "graphql.gen.ts"))) as Generated;
	return generated.createSchema(() => handlers, deps);
}

/** The emitted SDL against the schema the emitted module builds, through the shared oracle. */
async function agreementOf(outDir: string) {
	const schema = await runtimeSchemaOf(outDir);
	expect(validateSchema(schema)).toEqual([]);
	return sdlAgreement(readFileSync(join(outDir, "schema.graphql"), "utf8"), schema);
}

function messagesOf(compiled: CompiledFixture, code: string): readonly string[] {
	return compiled.messages
		.filter((m) => m.code === `typespec-http-graphql/${code}`)
		.map((m) => m.message);
}

describe("a bookshop service", () => {
	let compiled: CompiledFixture;
	beforeAll(async () => {
		compiled = await compileFixture(join(here, "bookshop"), "main", { outName: "emit-bookshop" });
	}, 300_000);

	it("compiles with no error, and nothing from this emitter to warn about", () => {
		expect(compiled.messages.filter((m) => m.code.startsWith("typespec-http-graphql/"))).toEqual(
			[],
		);
	});

	it("writes the three GraphQL files beside the library's validators", () => {
		for (const file of ["schemas.gen.ts", ...GRAPHQL_FILES]) {
			expect(existsSync(join(compiled.outDir, file)), file).toBe(true);
		}
	});

	it("copies the runtime byte for byte under the generated banner", () => {
		const emitted = readFileSync(join(compiled.outDir, "graphql-runtime.gen.ts"), "utf8");
		expect(emitted.startsWith("// GENERATED by typespec-http-graphql. DO NOT EDIT.\n")).toBe(true);
		expect(emitted.endsWith(readFileSync(runtimeSource, "utf8"))).toBe(true);
	});

	it("writes output that compiles under the settings a consumer builds with", () => {
		const { output, failed } = typecheckEmitted(compiled.outDir);
		expect(output).toBe("");
		expect(failed).toBe(false);
	});

	it("writes a schema.graphql that is the schema createSchema builds", async () => {
		const agreement = await agreementOf(compiled.outDir);
		expect(agreement.sdl).toBe(agreement.runtime);
		expect(agreement.disagreements).toEqual([]);
		// `@cost` on three root fields and three links, `@listSize` on the two connections.
		expect(agreement.applied).toBe(8);
	});

	it("declares exactly the surface graphql.tsp states", async () => {
		const schema = await runtimeSchemaOf(compiled.outDir);
		expect(Object.keys(schema.getQueryType()?.getFields() ?? {}).toSorted()).toEqual([
			"book",
			"books",
		]);
		expect(Object.keys(schema.getMutationType()?.getFields() ?? {})).toEqual(["createBook"]);
		const book = schema.getType("Book");
		if (!isObjectType(book)) throw new Error("Book is not an object type");
		// Every property of `Book` in rest.tsp in model order, by its wire name in camelCase,
		// then the three links main.tsp declares, by name (plan.ts orders links so a reordered
		// graphql.tsp prints the same schema): exactly these, so an extra field fails too.
		expect(Object.keys(book.getFields())).toEqual([
			"id",
			"title",
			"status",
			"authorId",
			"editorId",
			"createdAt",
			"author",
			"editions",
			"editor",
		]);
		// A required header is an input field; an optional one is never GraphQL input.
		const input = schema.getType("CreateBookInput");
		if (!isInputObjectType(input)) throw new Error("CreateBookInput is not an input type");
		expect(Object.keys(input.getFields())).toContain("xApiVersion");
		expect(Object.keys(input.getFields())).not.toContain("xRequestId");
	});

	/** End to end: wire names both ways, and a null binding calls nothing. */
	it("resolves through the emitted module, calling each handler with wire-shaped input", async () => {
		const calls: (readonly [string, unknown])[] = [];
		const record =
			(operationId: string, answer: unknown) =>
			(_ctx: unknown, input: unknown): unknown => {
				calls.push([operationId, input]);
				return answer;
			};
		const schema = await runtimeSchemaOf(compiled.outDir, {
			Books_read: record("Books_read", {
				status: 200,
				body: {
					id: "c1",
					title: "First",
					status: "in_print",
					author_id: "t1",
					editor_id: null,
					created_at: "2026-10-13T00:00:00Z",
				},
			}),
			Authors_read: record("Authors_read", { status: 200, body: { id: "t1", name: "Author one" } }),
			Editors_read: record("Editors_read", { status: 404, body: { message: "none" } }),
			BookEditions_list: record("BookEditions_list", {
				status: 200,
				body: { items: [{ id: "a1", book_id: "c1", name: "paperback" }] },
			}),
		});
		const result = await graphql({
			schema,
			contextValue: {},
			source: `{ book(id: "c1") {
				id createdAt
				author { name }
				editor { displayName }
				editions(first: 5) { nodes { name } pageInfo { hasNextPage } }
			} }`,
		});
		expect(result).toEqual({
			data: {
				book: {
					id: "c1",
					createdAt: "2026-10-13T00:00:00Z",
					author: { name: "Author one" },
					editor: null,
					editions: { nodes: [{ name: "paperback" }], pageInfo: { hasNextPage: false } },
				},
			},
		});
		expect(calls).toEqual([
			["Books_read", { id: "c1" }],
			["Authors_read", { authorId: "t1" }],
			["BookEditions_list", { bookId: "c1", "page-size": 5 }],
		]);
	});
});

describe("the same service under seal-object-schemas", () => {
	let compiled: CompiledFixture;
	beforeAll(async () => {
		compiled = await compileFixture(join(here, "bookshop"), "main", {
			outName: "emit-bookshop-sealed",
			extraOptions: { "seal-object-schemas": true },
		});
	}, 300_000);

	it("still compiles, and still agrees with its SDL", async () => {
		const { output, failed } = typecheckEmitted(compiled.outDir);
		expect(output).toBe("");
		expect(failed).toBe(false);
		const agreement = await agreementOf(compiled.outDir);
		expect(agreement.sdl).toBe(agreement.runtime);
		expect(agreement.disagreements).toEqual([]);
	});

	it("accepts a mutation's input through the sealed request schema, at its wire keys", async () => {
		const calls: unknown[] = [];
		const created = {
			id: "c2",
			title: "Second",
			status: "in_print",
			author_id: "t1",
			editor_id: null,
			created_at: "2026-10-13T00:00:00Z",
		};
		const schema = await runtimeSchemaOf(compiled.outDir, {
			Books_create: (_ctx: unknown, input: unknown) => {
				calls.push(input);
				return { status: 201, body: created };
			},
		});
		const result = await graphql({
			schema,
			contextValue: {},
			// The read-only `id` and `createdAt` are sent: the request is `Book`'s canonical schema.
			source: `mutation { createBook(input: {
				xApiVersion: "v1", id: "c2", title: "Second", status: IN_PRINT, authorId: "t1",
				editorId: null, createdAt: "2026-10-13T00:00:00Z"
			}) { __typename } }`,
		});
		expect(result).toEqual({ data: { createBook: { __typename: "Book" } } });
		expect(calls).toEqual([
			{
				"x-api-version": "v1",
				id: "c2",
				title: "Second",
				status: "in_print",
				author_id: "t1",
				editor_id: null,
				created_at: "2026-10-13T00:00:00Z",
			},
		]);
	});
});

describe("a service whose spec declares no GraphQL surface", () => {
	let compiled: CompiledFixture;
	beforeAll(async () => {
		// The REST file alone: graphql.tsp deleted, the emitter line kept.
		compiled = await compileFixture(join(here, "bookshop"), "rest", { outName: "emit-rest-only" });
	}, 300_000);

	it("writes the library's validators and no GraphQL file, not even the runtime", () => {
		expect(existsSync(join(compiled.outDir, "schemas.gen.ts"))).toBe(true);
		for (const file of GRAPHQL_FILES) {
			expect(existsSync(join(compiled.outDir, file)), file).toBe(false);
		}
	});

	it("warns no-fields-declared once, naming the service", () => {
		const warnings = messagesOf(compiled, "no-fields-declared");
		expect(warnings).toHaveLength(1);
		expect(warnings[0]).toContain("'Bookshop'");
	});
});

describe("three services in one program", () => {
	let compiled: CompiledFixture;
	beforeAll(async () => {
		compiled = await compileFixture(join(here, "multi"), "main", { outName: "emit-multi" });
	}, 300_000);

	const dirOf = (service: string) => join(compiled.outDir, service);

	it("writes each declaring service's files into a directory of its own", () => {
		for (const service of ["Widgets", "Gadgets"]) {
			for (const file of ["schemas.gen.ts", ...GRAPHQL_FILES]) {
				expect(existsSync(join(dirOf(service), file)), `${service}/${file}`).toBe(true);
			}
		}
	});

	it("writes no GraphQL file for the service that declares nothing, and warns about it alone", () => {
		expect(existsSync(join(dirOf("Gizmos"), "schemas.gen.ts"))).toBe(true);
		for (const file of GRAPHQL_FILES) {
			expect(existsSync(join(dirOf("Gizmos"), file)), `Gizmos/${file}`).toBe(false);
		}
		const warnings = messagesOf(compiled, "no-fields-declared");
		expect(warnings).toHaveLength(1);
		expect(warnings[0]).toContain("'Gizmos'");
	});

	it("gives each service its own root field and none of the other's", async () => {
		const widgets = await runtimeSchemaOf(dirOf("Widgets"));
		const gadgets = await runtimeSchemaOf(dirOf("Gadgets"));
		expect(Object.keys(widgets.getQueryType()?.getFields() ?? {})).toEqual(["widget"]);
		expect(Object.keys(gadgets.getQueryType()?.getFields() ?? {})).toEqual(["gadget"]);
	});

	it("writes, per service, output that compiles and a schema.graphql that is its schema", async () => {
		for (const service of ["Widgets", "Gadgets"]) {
			const { output, failed } = typecheckEmitted(dirOf(service));
			expect(output, service).toBe("");
			expect(failed, service).toBe(false);
			const agreement = await agreementOf(dirOf(service));
			expect(agreement.sdl, service).toBe(agreement.runtime);
			expect(agreement.disagreements, service).toEqual([]);
			expect(agreement.applied, service).toBe(1);
		}
	});
});
