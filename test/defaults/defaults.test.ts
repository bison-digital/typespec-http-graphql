import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { beforeAll, describe, expect, it } from "vitest";
import { compileFixture, type CompiledFixture } from "../support/compile-fixture.js";
import { typecheckEmitted } from "../support/typecheck-emitted.js";

/**
 * **What one compile writes, with nothing configured but the output directory**: the configuration
 * the README produces.
 *
 * The runtime is COPIED beside the generated code rather than imported from this package, because
 * a consumer installs an emitter as a devDependency and an emitted import of it is a deployment that
 * fails at run time and nowhere earlier.
 */

const here = fileURLToPath(new URL(".", import.meta.url));
const runtimeSource = fileURLToPath(new URL("../../src/runtime.ts", import.meta.url));

let compiled: CompiledFixture;
beforeAll(async () => {
	compiled = await compileFixture(here, "service");
}, 300_000);

describe("what one compile writes", () => {
	it("writes the library's validators beside this package's runtime", () => {
		expect(existsSync(join(compiled.outDir, "schemas.gen.ts"))).toBe(true);
		expect(existsSync(join(compiled.outDir, "graphql-runtime.gen.ts"))).toBe(true);
	});

	it("copies the runtime byte for byte under a generated banner", () => {
		const emitted = readFileSync(join(compiled.outDir, "graphql-runtime.gen.ts"), "utf8");
		const source = readFileSync(runtimeSource, "utf8");
		expect(emitted.startsWith("// GENERATED by typespec-http-graphql. DO NOT EDIT.\n")).toBe(true);
		expect(emitted.endsWith(source)).toBe(true);
		// Non-vacuity: an empty source would end every file.
		expect(source.length).toBeGreaterThan(0);
	});

	it("writes the schema module and its SDL beside them, for the one field the spec declares", () => {
		expect(existsSync(join(compiled.outDir, "graphql.gen.ts"))).toBe(true);
		expect(existsSync(join(compiled.outDir, "schema.graphql"))).toBe(true);
		expect(readFileSync(join(compiled.outDir, "schema.graphql"), "utf8")).toContain("widget(id: ");
	});

	it("never writes a sibling emitter's runtime file name", () => {
		expect(existsSync(join(compiled.outDir, "runtime.gen.ts"))).toBe(false);
		expect(existsSync(join(compiled.outDir, "mcp-runtime.gen.ts"))).toBe(false);
	});

	it("writes output that compiles under the settings a consumer builds with", () => {
		const { output, failed } = typecheckEmitted(compiled.outDir);
		expect(output).toBe("");
		expect(failed).toBe(false);
	});
});
